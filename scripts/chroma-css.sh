#!/usr/bin/env bash
# Generates assets/css/chroma.css from a light and a dark Chroma style. Every colour becomes
# light-dark(light, dark), so code blocks follow color-scheme like the rest of the site and the theme
# switch needs no extra rules. Other properties (bold, italic, ...) cannot switch with the scheme and
# are kept only where both styles agree. Block background and text colour come from main.css.
#
#   scripts/chroma-css.sh [light-style] [dark-style]      (defaults: github github-dark)
#
# Styles: https://xyproto.github.io/splash/docs/
set -euo pipefail

light=${1:-github}
dark=${2:-github-dark}
out="$(dirname "$0")/../assets/css/chroma.css"

{
  echo "/* Generated by scripts/chroma-css.sh $light $dark. Do not edit by hand. */"
  awk '
    FNR == 1 { mode++ }
    /\{/ {
      sel = $0; sub(/^\/\*[^*]*\*\/ */, "", sel); sub(/ *\{.*$/, "", sel)
      if (sel == ".bg") next
      body = $0; sub(/^[^{]*\{/, "", body); sub(/\}.*$/, "", body)
      n = split(body, parts, ";")
      for (i = 1; i <= n; i++) {
        p = parts[i]; c = index(p, ":"); if (c == 0) continue
        k = substr(p, 1, c - 1); v = substr(p, c + 1)
        gsub(/^ +| +$/, "", k); gsub(/^ +| +$/, "", v)
        if (sel == ".chroma" && k ~ /color$/) continue
        if (!(sel in seen)) { seen[sel] = 1; order[++ns] = sel }
        if (!((sel, k) in seenk)) { seenk[sel, k] = 1; keys[sel] = keys[sel] "|" k }
        val[mode, sel, k] = v
      }
    }
    END {
      for (i = 1; i <= ns; i++) {
        sel = order[i]; decl = ""
        nk = split(substr(keys[sel], 2), ks, "|")
        for (j = 1; j <= nk; j++) {
          k = ks[j]
          if (k ~ /color$/) {
            missing = (k == "color") ? "currentColor" : "transparent"
            l = ((1, sel, k) in val) ? val[1, sel, k] : missing
            d = ((2, sel, k) in val) ? val[2, sel, k] : missing
            v = (l == d) ? l : "light-dark(" l ", " d ")"
          } else if (((1, sel, k) in val) && ((2, sel, k) in val) && val[1, sel, k] == val[2, sel, k]) {
            v = val[1, sel, k]
          } else {
            continue
          }
          decl = decl " " k ": " v ";"
        }
        if (decl != "") print sel " {" decl " }"
      }
    }
  ' <(hugo gen chromastyles --style="$light") <(hugo gen chromastyles --style="$dark")
} > "$out"
